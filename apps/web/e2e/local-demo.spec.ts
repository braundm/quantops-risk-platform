import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import type { StockUsers } from "../src/lib/stockUsers";
import type { XtbAccounts } from "../src/lib/xtbAccounts";

test("default accounts isolate the empty portfolio from the supplied synthetic workbook", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByLabel("Lokalne konta testowe")).toContainText("admin1 / admin1");
  await page.getByLabel("Login", { exact: true }).fill("admin");
  await page.getByLabel("Hasło", { exact: true }).fill("admin");
  await page.getByRole("button", { name: "Otwórz mój portfel" }).click();
  await expect(page.getByRole("heading", { name: "Dodaj pierwszy rachunek" })).toBeVisible();
  await page.getByRole("button", { name: "Wyloguj się", exact: true }).click();
  await page.getByLabel("Login", { exact: true }).fill("admin1");
  await page.getByLabel("Hasło", { exact: true }).fill("admin1");
  await page.getByRole("button", { name: "Otwórz mój portfel" }).click();
  await expect(page.getByRole("note").filter({ hasText: "Konto testowe" })).toContainText("SYNTHETIC");
  const navigation = page.getByRole("navigation", { name: "Centrum portfela" });
  await navigation.getByRole("button", { name: "Portfel", exact: true }).click();
  const positions = page.getByRole("region", { name: "Otwarte pozycje XTB", exact: true });
  await expect(positions.getByRole("row")).toHaveCount(10);
  await expect(positions).toContainText("CDR.PL");
  await expect(positions).toContainText("EUNL.DE");
  await expect(positions.getByText("Czeka na cenę", { exact: true })).toHaveCount(9);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `../../artifacts/default-portfolio-${test.info().project.name}.png`, fullPage: true });
  await navigation.getByRole("button", { name: "Historia importów", exact: true }).click();
  await expect(page.getByText("1 raportów · 122 unikalnych zapisów.", { exact: false })).toBeVisible();
  await expect(page.getByRole("region", { name: "Zaimportowane raporty" })).toContainText("quantum_ops_portfolio_test.xlsx");
  const before = await page.evaluate(() => {
    const registry = JSON.parse(localStorage.getItem("quantops.stock-users.v1")!) as StockUsers;
    const owner = registry.users.find(user => user.credentials?.login === "admin1")!;
    const key = `quantops.xtb-books.v1.${owner.id}`;
    const accounts = JSON.parse(localStorage.getItem(key)!) as XtbAccounts;
    accounts.accounts[0]!.label = "Synthetic retained edit";
    localStorage.setItem(key, JSON.stringify(accounts));
    return { key, records: accounts.accounts[0]!.book.records.length };
  });
  expect(before.records).toBe(122);
  await page.reload();
  const after = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!) as XtbAccounts, before.key);
  expect(after.accounts).toHaveLength(1);
  expect(after.accounts[0]!.label).toBe("Synthetic retained edit");
  expect(after.accounts[0]!.imports).toHaveLength(1);
  expect(after.accounts[0]!.book.records).toHaveLength(122);
});
